    /// The bug this whole exercise exists for: a patch record whose install folder
    /// moved. Relink must re-point the record AND its backups, otherwise a later
    /// Unpatch writes the game's original DLLs back into a directory that no longer
    /// exists and the record can never be cleared.
    #[test]
    fn relink_rebases_record_and_backups_onto_new_folder() {
        let game_dir = tmpdir("relink_old");
        let cache = tmpdir("relink_cache");
        let state_dir = tmpdir("relink_state");
        let original = "ORIGINAL VERSION.DLL CONTENT";
        write(&game_dir.join("version.dll"), original);

        let req = make_request(&game_dir, &cache, &state_dir);
        let mut rec = install(&req).expect("install should succeed");
        assert_eq!(rec.backed_up.len(), 1, "original must be backed up");
        let old_backup = rec.backed_up[0].backup_path.clone();

        // The game folder moves to a brand new location, old one vanishes.
        let moved = tmpdir("relink_new");
        write(&moved.join("Game-Win64-Shipping.exe"), "fake exe");
        write(&moved.join("version.dll"), &read(&game_dir.join("version.dll")));
        write(
            &moved.join(crate::download::INI_NAME),
            &read(&game_dir.join(crate::download::INI_NAME)),
        );
        // A 0.4.0 record is only "patched" while its runtime tree sits beside the exe, so the
        // moved folder needs its own copy or `looks_patched` below would report a repatch.
        crate::download::copy_dir_recursive(
            &cache.join(crate::download::RUNTIME_DIR_NAME),
            &moved.join(crate::download::RUNTIME_DIR_NAME),
        )
        .unwrap();
        fs::remove_dir_all(&game_dir).unwrap();

        relink_record(&mut rec, &moved.join("Game-Win64-Shipping.exe"));

        assert_eq!(
            PathBuf::from(&rec.render_exe),
            moved.join("Game-Win64-Shipping.exe"),
            "record must point at the new location"
        );
        assert_eq!(
            PathBuf::from(&rec.backed_up[0].original_path),
            moved.join("version.dll"),
            "the restore target must be rebased onto the new folder"
        );
        assert_eq!(
            rec.backed_up[0].backup_path, old_backup,
            "the backup file itself must NOT move - only where it gets restored to"
        );
        assert!(looks_patched(&rec), "the moved folder still holds our files");

        // And the payoff: Unpatch now restores the original in the NEW folder.
        uninstall(&rec).expect("uninstall after relink should succeed");
        assert_eq!(read(&moved.join("version.dll")), original);
        assert!(!moved.join(crate::download::INI_NAME).exists());
    }

